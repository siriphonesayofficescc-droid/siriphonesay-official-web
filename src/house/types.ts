/**
 * Data model for the parametric house designer.
 * A Design is plain JSON: it is saved locally, shared in links, stored in
 * Supabase (designs.data jsonb) and fully regenerates the 3D model.
 */

export type StyleId =
  | 'modern'
  | 'modern-luxury'
  | 'contemporary'
  | 'minimalist'
  | 'tropical'
  | 'european'
  | 'classic'
  | 'modern-classic'
  | 'industrial'
  | 'scandinavian'
  | 'japanese'
  | 'lao'
  | 'two-storey-modern'
  | 'three-storey-luxury'
  | 'custom'

export type RoofType = 'flat' | 'gable' | 'hip' | 'shed'
export type StairPos = 'left' | 'center' | 'right'
export type FinishLevel = 'standard' | 'premium' | 'luxury'

export type RoomType =
  | 'master_bed' | 'bed' | 'guest_bed' | 'kids_bed' | 'walkin' | 'dressing'
  | 'master_bath' | 'bath' | 'guest_bath'
  | 'living' | 'family' | 'entertainment' | 'lounge'
  | 'dining' | 'kitchen' | 'kitchen2' | 'pantry' | 'laundry' | 'storage' | 'office'
  | 'prayer' | 'fitness' | 'maid' | 'utility' | 'garage'
  | 'hall' // circulation (generated, not selectable)

/** A requested room (type × quantity on a floor). Floors are 0-based. */
export interface RoomRequest {
  type: RoomType
  floor: number
  qty: number
}

export interface FurnitureItem {
  id: string
  kind: string
  floor: number
  x: number // building-local metres (origin = building centre, +z = front)
  z: number
  rot: number // radians
  scale: number // 0.8–1.2
  color?: string
  roomId?: string
  auto?: boolean // generated by auto-furnish (replaced when rooms change)
}

export interface RoomOverride {
  floorMat?: string
  wallColor?: string
  name?: string
}

export interface Facade {
  /** the side shown in the reference photo (gets the glass, frames and fins) */
  side: 'front' | 'back'
  /** ground floor set back under the upper floor on the main side (m, 0 = flush) */
  recess: number
  glass: 'normal' | 'wide' | 'wall'
  glassFloors: 'ground' | 'all'
  glassSides: 'main' | 'both'
  /** black frame divisions on large glass */
  grid: boolean
  /** thick projecting frame around the upper floor(s) or the whole façade */
  frame: 'none' | 'upper' | 'whole'
  frameMat: string
  frameColor: string
  frameDepth: number
  /** thick projecting band at each upper floor level */
  band: boolean
  bandMat: string
  bandColor: string
  /** vertical fins on the upper floor */
  fins: 'none' | 'left' | 'right' | 'center'
  finsMat: string
  finsColor: string
  pergola: boolean
  deck: boolean
}

export interface Design {
  version: 1
  ref: string // project reference, e.g. SCC-26-4F7K
  name: string
  style: StyleId
  createdAt: string
  updatedAt: string

  land: { w: number; l: number }
  building: { w: number; l: number }
  floors: 1 | 2 | 3
  ceiling: number // clear ceiling height (m)
  roof: { type: RoofType; pitch: number; overhang: number }
  stair: StairPos
  arrangement: 'standard' | 'private-front' | 'mirrored'
  /** Floor-plan variant seed — 'Generate another plan' changes it */
  planSeed?: number
  /** Seeds the customer marked as favourite */
  favoritePlans?: number[]
  /** Random exterior look — 'Generate exterior' changes it */
  lookSeed?: number
  lookName?: string
  favoriteLooks?: { seed: number; character: string; name: string }[]
  /** The customer's written description, if the house was generated from a prompt */
  prompt?: string
  /** Façade features (photo matching): overhangs, frames, bands, fins, glass walls, pergola, deck */
  facade?: Facade
  /** AI-generated 3D model (GLB) made from the customer's reference photo — look only, not editable */
  aiModelUrl?: string
  entrance: 'front' | 'side'
  rearEntrance: boolean
  balcony: { enabled: boolean; depth: number }
  terrace: { enabled: boolean } // roof terrace (flat roof) or ground terrace
  parking: number // car spaces (carport on land)
  windowRatio: number // 0.6 – 1.4 window size multiplier

  rooms: RoomRequest[]
  roomOverrides: Record<string, RoomOverride>

  exterior: {
    wall: string
    wallColor: string
    accent: string
    accentColor: string
    roof: string
    roofColor: string
    frame: string
    glass: string
    door: string
    garageDoor: string
    fence: string
    gate: string
    lights: boolean
  }
  interior: {
    theme: string
    floorLiving: string
    floorBed: string
    floorWet: string
    wallColor: string
    featureWall: string
    ceiling: string
    stairFinish: string
    handrail: string
    doorFinish: string
    lighting: string
  }
  extras: { pool: boolean; poolSize: [number, number]; garden: boolean; trees: number }
  finish: FinishLevel
  furniture: FurnitureItem[]
  notes: string
}

/* ── generated layout ─────────────────────────────────────────── */
export interface Rect {
  x0: number
  z0: number
  x1: number
  z1: number
}

export interface PlacedRoom extends Rect {
  id: string
  type: RoomType | 'stair'
  floor: number
  label: string
}

export interface Issue {
  level: 'error' | 'warning'
  message: string
  messageLo?: string
}

/**
 * Compact U-turn (dog-leg) stair. Local frame: origin at the open end
 * (where you step on and arrive), u = direction of flight 1, v = across.
 * Flight 1: v ∈ [0, fw], u 0→run (up to the landing). Landing: u ∈ [run, run+landing].
 * Flight 2: v ∈ [width−fw, width], u run→0 (arrives at the open end, one floor up).
 */
export interface StairDef extends Rect {
  ox: number
  oz: number
  ux: number
  uz: number
  vx: number
  vz: number
  run: number
  landing: number
  width: number
  flightW: number
  n: number
  /** the open edge (no wall) as a partition line: axis 'x' = line of constant z, 'z' = constant x */
  openEdge: { axis: 'x' | 'z'; c: number; a: number; b: number }
}

export interface Layout {
  W: number
  L: number
  floorH: number
  floors: PlacedRoom[][]
  stair: StairDef | null
  issues: Issue[]
  gfa: number
  /** living/dining/kitchen open to each other */
  openPlan: boolean
  /** short human description of the generated variant */
  variant: string
  seed: number
}
